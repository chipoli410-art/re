import pandas as pd

# 1. 병합된 데이터 불러오기
print("데이터를 불러오는 중입니다...")
df = pd.read_csv('preprocessed_1year_merged_final.csv')

# ---------------------------------------------------------
# 2. 📅 시간 및 달력 파생 변수 생성
# ---------------------------------------------------------
print("시간 및 달력 변수를 생성합니다...")
df['날짜_dt'] = pd.to_datetime(df['대여일자'].astype(str), format='%Y%m%d')

df['월'] = df['날짜_dt'].dt.month
df['요일'] = df['날짜_dt'].dt.dayofweek  # 0:월요일 ~ 6:일요일
df['주말_여부'] = df['요일'].apply(lambda x: 1 if x >= 5 else 0)

# ---------------------------------------------------------
# 3. ☀️ 기상 파생 변수 생성
# ---------------------------------------------------------
print("기상 파생 변수를 생성합니다...")
df['비옴_여부'] = df['강수량'].apply(lambda x: 1 if x > 0 else 0)

# ---------------------------------------------------------
# 4. 📈 시계열 파생 변수 생성 (모델 성능 향상의 핵심!)
# ---------------------------------------------------------
print("시계열 파생 변수(Lag & Rolling)를 생성합니다... (데이터 정렬로 인해 수 초~수 분 소요)")

# [매우 중요] 과거 데이터를 밀어내기(shift) 전, 반드시 대여소와 시간순으로 정렬!
df = df.sort_values(by=['대여소_ID', '날짜_dt', '대여시간(시)']).reset_index(drop=True)

# 1시간 전 대여건수 (직전 시간의 수요 파악)
df['Lag_1h'] = df.groupby('대여소_ID')['총_대여건수(Y)'].shift(1)

# 24시간 전 대여건수 (어제 똑같은 시간대의 수요 파악)
df['Lag_24h'] = df.groupby('대여소_ID')['총_대여건수(Y)'].shift(24)

# 168시간 전 대여건수 (일주일 전 똑같은 요일/시간대의 수요 파악)
df['Lag_168h'] = df.groupby('대여소_ID')['총_대여건수(Y)'].shift(168)

# 최근 3시간 평균 대여건수 (미래 정답을 훔쳐보지 않도록 shift(1)을 먼저 적용)
df['Rolling_Mean_3h'] = df.groupby('대여소_ID')['총_대여건수(Y)'].transform(lambda x: x.shift(1).rolling(window=3).mean())

# ---------------------------------------------------------
# 5. 🚲 대여소 ID 숫자로 인코딩
# ---------------------------------------------------------
print("대여소 ID를 모델이 인식할 수 있게 숫자로 변환합니다...")
df['대여소_ID_num'] = df['대여소_ID'].astype('category').cat.codes

# ---------------------------------------------------------
# 6. 결측치 제거 및 최종 정리
# ---------------------------------------------------------
# Lag_168h 변수로 인해 각 대여소의 첫 7일치 데이터는 과거 기록이 없어 NaN(결측치)이 됩니다.
# 머신러닝 모델 에러를 방지하기 위해 이 빈칸이 있는 행들을 과감히 삭제합니다.
print("과거 기록이 없는 초기 7일치 결측치 데이터를 제거합니다...")
df_ml_ready = df.dropna().reset_index(drop=True)

# 예측에 사용할 핵심 변수만 남기기
features_to_keep = [
    '대여소_ID_num', '월', '요일', '대여시간(시)', '주말_여부', 
    '기온', '강수량', '풍속', '습도', '비옴_여부', 
    'Lag_1h', 'Lag_24h', 'Lag_168h', 'Rolling_Mean_3h', # 추가된 시계열 변수
    '총_대여건수(Y)' 
]
final_df = df_ml_ready[features_to_keep]

# 7. 최종 파일 저장
output_filename = 'ml_ready_bike_data_advanced.csv'
final_df.to_csv(output_filename, index=False, encoding='utf-8-sig')

print(f"\n🎉 특성 공학 완료! 고성능 모델 학습을 위한 '{output_filename}' 파일이 생성되었습니다.")
print(f"최종 학습 데이터 형태: {final_df.shape}")